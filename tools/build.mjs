import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=name=>fs.readFileSync(path.join(root,'src',name),'utf8');
let html=read('index.template.html');
for(const [marker,name] of [['STYLES','styles.css'],['RULES','rules.json'],['MENUS','menus.js'],['CORE','core.js'],['CLOUD','cloud.js'],['PRACTICE','practice.js'],['APP','app.js']])html=html.replace('__'+marker+'__',()=>read(name));
const config=JSON.parse(fs.readFileSync(path.join(root,'config.json'),'utf8'));
if(config.apiUrl&&!/^https:\/\/script\.google\.com\/macros\/s\/[A-Za-z0-9_-]+\/exec$/.test(config.apiUrl))throw new Error('Invalid Apps Script API URL');
html=html.replace('__CONFIG__',()=>JSON.stringify(config).replaceAll('<','\\u003c'));
if(/__[A-Z]+__/.test(html))throw new Error('Unfilled template marker');
fs.mkdirSync(path.join(root,'public'),{recursive:true});
fs.writeFileSync(path.join(root,'index.html'),html);
fs.writeFileSync(path.join(root,'public','index.html'),html);
fs.writeFileSync(path.join(root,'public','.nojekyll'),'');
fs.mkdirSync(path.join(root,'backend'),{recursive:true});
fs.writeFileSync(path.join(root,'backend','Menus.gs'),read('menus.js'));
fs.writeFileSync(path.join(root,'backend','Core.gs'),read('core.js'));
console.log('Built root index.html, public/index.html and Apps Script calculation modules.');
